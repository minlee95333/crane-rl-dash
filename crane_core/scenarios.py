from crane_core.scenarios_data import SCEN_SPECS

# The easiest ★1 scenario doubles as the tutorial walkthrough entry point.
_WALKTHROUGH_ID = next((s["id"] for s in SCEN_SPECS if int(s.get("difficulty", 9)) == 1), None)

def _register_spec(spec: Dict) -> None:
    """Turn a SCEN_SPECS-shaped dict into a runnable SCENARIOS entry."""
    SCENARIOS[spec["id"]] = {
        "id": spec["id"],
        "tier": spec["tier"],
        "name": spec["name"],
        "description": spec["description"],
        "difficulty": int(spec["difficulty"]),
        "walkthrough": spec["id"] == _WALKTHROUGH_ID,
        # When True, PlaySession imposes a seeded-random erection order on this
        # scenario (dedicated "순서" maps). Absent/False on ordinary maps.
        "order_mode": bool(spec.get("order_mode", False)),
        "layout": spec["layout"],
        "config": _default_config(crane_radius=float(spec.get("cr", 20.0))),
    }
    # Fleet-sizing maps: {"min": int, "max": int} — the player picks the crane
    # count (and parks each crane) before the session starts. Absent elsewhere.
    if spec.get("crane_choice"):
        SCENARIOS[spec["id"]]["crane_choice"] = dict(spec["crane_choice"])


SCENARIOS: Dict[str, Dict] = {}
for _spec in SCEN_SPECS:
    _register_spec(_spec)

