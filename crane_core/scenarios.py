# Ordered ("순서") scenarios — dedicated maps the player works in a fixed,
# seeded-random erection order (no client toggle). Each clones a tuned base map
# so geometry/weights/heights are already balanced, then flips on order_mode;
# PlaySession reads that flag and gates candidates to the next-K in order. Built
# AFTER the height/weight passes so the clone inherits the finalized layout.
# ─────────────────────────────────────────────────────────────────────────────
# ``order_count`` = how many lifts carry the order; the rest are free. The
