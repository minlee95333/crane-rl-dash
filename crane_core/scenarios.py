"""Fixed scenario pool for the human-play (gamification) tab.

Each scenario is a self-contained layout (cranes / lifts / restricted zones)
plus env config. Scenarios are DATA-DRIVEN now: 21 maps over difficulty 1-5
(counts 3/5/5/5/3), generated by ``_gen_scenarios.py`` into
``crane_core/scenarios_data.py``. Edit coordinates there to tune.

- ``difficulty`` (1-5 → ★ stars) is the primary axis. As it rises: more cranes/
  lifts, more restricted zones, wider weight/height spread, and (from ★3) some
  lifts placed INSIDE restricted zones (crane stands outside, boom reaches in).
- ``tier`` is a coarse 3-band grouping for the list filter only:
  tutorial=★1-2 (입문), standard=★3 (표준), expert=★4-5 (고급).

A scenario layout/config is dicts only (no env instance) so it can be
serialized to JSON and re-used by both /api/game/scenarios (frontend list)
and /api/game/session/* (session creation).
"""
from __future__ import annotations

import copy
from typing import Dict, List, Optional


# Reasonable rated-load curve for the expert tier. (radius_m, capacity_t)
# Points should be sorted by radius; capacity decreases as radius grows.
EXPERT_CAPACITY_CURVE = [
    [8.0, 28.0],
    [12.0, 22.0],
    [16.0, 16.0],
    [20.0, 11.0],
    [24.0, 7.0],
]


# 2D rated-load chart (boom-length × radius), the mobile-crane standard format and
# the DEFAULT rated-load model for every scenario. One capacity-vs-radius curve per
# boom length: extending the boom to reach higher (or farther) derates capacity at
# the same horizontal radius. Reaching radius R at height H needs a boom of slant
# length sqrt(R²+H²); the env picks the SHORTEST boom that covers it (most capacity)
# and reads capacity at R from that boom's curve. The longest boom (42m) sets the
# absolute reach limit. The shortest boom is 13m (a real 50t main-boom minimum) so
# placement heights in the 8–18m range actually push a close-in lift onto a longer
# boom and derate it. Radius range reaches 27m to cover the largest crane_radius.
DEFAULT_CAPACITY_CHART = [
    {"boom_len": 13.0, "curve": [[3, 50], [6, 42], [9, 33], [12, 26]]},
    {"boom_len": 22.0, "curve": [[3, 46], [6, 38], [9, 30], [12, 24], [15, 18], [18, 13], [21, 10]]},
    {"boom_len": 32.0, "curve": [[3, 40], [6, 32], [9, 24], [12, 19], [15, 14], [18, 10], [24, 6]]},
    {"boom_len": 42.0, "curve": [[3, 34], [6, 26], [9, 19], [12, 15], [15, 10], [18, 7],  [27, 4]]},
]

# Back-compat alias — earlier code referenced EXPERT_CAPACITY_CHART.
EXPERT_CAPACITY_CHART = DEFAULT_CAPACITY_CHART


def _default_config(
    fixed_duration: float = 25.0,
    setup_time: float = 10.0,
    teardown_time: float = 5.0,
    crane_radius: float = 18.0,
    site_size: float = 100.0,
    candidate_k: int = 999,  # human play: unrestricted candidate list
    max_steps: int = 220,
    crane_capacity_curve: Optional[List[List[float]]] = None,
    lift_weight_min_t: float = 0.0,
    lift_weight_max_t: float = 50.0,
    # 2.5D height parameters
    crane_boom_len: float = 0.0,   # default boom length (m); 0 = 2D mode
    lift_z_min: float = 0.0,       # random lift departure/arrival height range (m)
    lift_z_max: float = 0.0,
    crane_capacity_chart: Optional[List[Dict]] = DEFAULT_CAPACITY_CHART,  # 2D rated-load chart (default model); supersedes the 1D curve
) -> Dict:
    cfg = {
        "fixed_duration": fixed_duration,
        "setup_time": setup_time,
        "teardown_time": teardown_time,
        "crane_radius": crane_radius,
        "candidate_k": candidate_k,
        "max_steps": max_steps,
        "site_width": site_size,
        "site_height": site_size,
        "lift_weight_min_t": lift_weight_min_t,
        "lift_weight_max_t": lift_weight_max_t,
        "default_lift_weight_t": 10.0,
        "crane_boom_len": crane_boom_len,
        "lift_z_min": lift_z_min,
        "lift_z_max": lift_z_max,
    }
    if crane_capacity_curve:
        cfg["crane_capacity_curve"] = crane_capacity_curve
    if crane_capacity_chart:
        cfg["crane_capacity_chart"] = crane_capacity_chart
    return cfg


