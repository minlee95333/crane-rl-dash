# Tier groups for the frontend list view (coarse 3-band over the 5-star scale)
TIER_ORDER = ["tutorial", "standard", "expert"]
TIER_LABEL = {
    "tutorial": "입문",
    "standard": "표준",
    "expert": "고급",
}


def list_scenarios(tier: Optional[str] = None) -> List[Dict]:
    """Return scenario metadata (id, tier, name, description, difficulty,
    counts). Excludes full layout to keep the list payload small.

    Pass tier=None to get all scenarios sorted by tier then difficulty then id.
    """
    out = []
    for s in SCENARIOS.values():
        if tier and s["tier"] != tier:
            continue
        out.append({
            "id": s["id"],
            "tier": s["tier"],
            "tier_label": TIER_LABEL.get(s["tier"], s["tier"]),
            "name": s["name"],
            "description": s["description"],
            "difficulty": s["difficulty"],
            "num_cranes": len(s["layout"]["cranes"]),
            "num_lifts": len(s["layout"]["lifts"]),
            "num_restricted": len(s["layout"]["restrictedZones"]),
            "walkthrough": bool(s.get("walkthrough", False)),
            "order_mode": bool(s.get("order_mode", False)),
            # fleet-sizing maps only; clients use it to show the placement step
            # (PC) or hide the card (mobile). None elsewhere keeps payload flat.
            "crane_choice": (dict(s["crane_choice"]) if s.get("crane_choice") else None),
        })
    # Sort by tier band, then difficulty, then walkthrough-first, then id.
    out.sort(key=lambda s: (
        TIER_ORDER.index(s["tier"]) if s["tier"] in TIER_ORDER else 99,
        s["difficulty"],
        0 if s.get("walkthrough") else 1,
        s["id"],
    ))
    return out


def get_scenario(scenario_id: str) -> Optional[Dict]:
    """Return a deep copy of a scenario by id, or None if not found.
    Deep copy so callers can mutate without affecting the registry.

    IDs that start with ``usr_`` are user-created scenarios stored in
    Postgres (see crane_db.storage.user_scenarios); we resolve those
    here so existing callers (human_play.create_session, etc.) keep
    working without branching on the id."""
    if scenario_id and scenario_id.startswith("usr_"):
        from crane_db import storage as _storage
        custom = _storage.get_user_scenario(scenario_id)
        return _storage.user_scenario_to_play_format(custom) if custom else None
    s = SCENARIOS.get(scenario_id)
    return copy.deepcopy(s) if s else None


def _diversify_standard(scenarios: Dict[str, Dict]) -> None:
    """Give STANDARD-tier lifts a spread of weights (and matching heights) so each
    lift's rated radius differs — the authored standard scenarios used a single
    uniform weight, which made every liftable-radius identical and hid the 2.5D
    effect. Tutorial (kept simple/uniform) and expert (already varied) are untouched.

    Weight cycle 8/12/16/20 t maps to distinct radii (~21/18/15/12 m at ground).
    Height is assigned INVERSELY to weight (light loads go high so height also bites,
    heavy loads stay low so they remain liftable after the crane repositions).
    Runs BEFORE _apply_tier_default_heights, which then leaves these z values alone.
    """
    weight_cycle = [8.0, 12.0, 16.0, 20.0]
    height_for = {8.0: 16.0, 12.0: 10.0, 16.0: 4.0, 20.0: 0.0}
    for scen in scenarios.values():
        if scen.get("tier") != "standard":
            continue
        for i, lift in enumerate(scen["layout"]["lifts"]):
            w = weight_cycle[i % len(weight_cycle)]
            lift["weight_t"] = w
            if "z" not in lift:
                lift["z"] = height_for[w]


def _apply_tier_default_heights(scenarios: Dict[str, Dict]) -> None:
    """Give every fixed-scenario lift a sample placement height (z) so the 2D
    rated-load chart actually engages across all tiers. Deterministic and editable:
    set `z` explicitly on a lift in its layout to override.

    Design intent (CLAUDE.md): tutorials stay at ground level so learners don't hit
    rated-load failures; standard gets modest heights; expert gets meaningful ones,
    but assigned INVERSELY to weight (heavy loads stay low) so every lift remains
    liftable once the crane repositions closer.
    """
    standard_cycle = [0.0, 4.0, 8.0]
    for scen in scenarios.values():
        tier = scen.get("tier")
        for i, lift in enumerate(scen["layout"]["lifts"]):
            if "z" in lift:
                continue  # respect explicit per-lift height
            if tier == "tutorial":
                z = 0.0
            elif tier == "standard":
                z = standard_cycle[i % len(standard_cycle)]
            else:  # expert: heavier loads placed lower to keep them feasible
                w = float(lift.get("weight_t", 10.0))
                z = 16.0 if w <= 10.0 else (10.0 if w <= 16.0 else 4.0)
            lift["z"] = z


_diversify_standard(SCENARIOS)
_apply_tier_default_heights(SCENARIOS)


